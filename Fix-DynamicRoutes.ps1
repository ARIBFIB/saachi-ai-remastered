$webRoot    = Join-Path $RepoRoot "apps\web"

function Write-Section {
    param([string]$Title)
    Write-Host ""
    Write-Host "==== $Title ====" -ForegroundColor Cyan
}

function New-DirSafe {
    param([string]$Path)
    if ([string]::IsNullOrWhiteSpace($Path)) { return }
    [System.IO.Directory]::CreateDirectory($Path) | Out-Null
}

function Backup-File {
    param([string]$Path)
    if (-not (Test-Path -LiteralPath $Path)) { return }
    $relative = $Path.Substring($RepoRoot.Length).TrimStart('\')
    $dest = Join-Path $backupRoot $relative
    New-DirSafe -Path (Split-Path $dest)
    Copy-Item -LiteralPath $Path -Destination $dest -Force
}

# Writes (or previews) a brand-new/replaced file, backing up any existing
# version first. $Lines is an array of raw lines (already `n`-joined by caller).
function Write-TargetFile {
    param(
        [string]$RelativePath,
        [string]$Content,
        [string]$Label
    )
    $full = Join-Path $webRoot $RelativePath
    New-DirSafe -Path (Split-Path $full)

    if (-not $WhatIfOnly) {
        if (Test-Path -LiteralPath $full) { Backup-File -Path $full }
        [System.IO.File]::WriteAllText($full, $Content, [System.Text.UTF8Encoding]::new($false))
    }
    Write-Host "  Wrote: $Label" -ForegroundColor Green
}

if (-not (Test-Path -LiteralPath $webRoot)) {
    Write-Host "Could not find apps\web under '$RepoRoot'. Run this script from the SAI2 repo root." -ForegroundColor Red
    exit 1
}

New-DirSafe -Path $backupRoot
Write-Host "Backups will be written to: $backupRoot" -ForegroundColor DarkGray

