HOW CATEGORY B IS FIXED

  Pages that were already Server Components (courses/[slug], categories/[slug],
  instructors/[slug]) are patched in place: params is now awaited, and the
  resolved slug is used to look up real data from DUMMY_COURSES
  (@saachi/api-client) instead of showing hardcoded content.

  Pages that are Client Components ("use client" + useState) CANNOT simply
  `await` a Promise prop. Next.js's own recommended pattern is to split them:
    - page.tsx becomes a small async Server Component that awaits params
      and passes the resolved value down as a normal prop
    - all the original interactive JSX moves, unchanged, into a new
      <Name>Client.tsx file in the same folder, which now accepts that
      value as a prop and uses it to look up the right record

  A new shared helper, apps\web\lib\instructor-lookup.ts, derives an
  "instructor" record (name, avatar, bio, courses) from DUMMY_COURSES by
  slugifying instructor.fullName, since there is no dedicated instructors
  dataset yet. Both the instructor profile page and the mentorship booking
  page use it, so they stay consistent.

KNOWN REMAINING LIMITATIONS (not fixed by this script, flagged so nothing
is silently swept under the rug):
  - CourseCurriculum and WhatYoullLearn (components\course-detail\*) still
    render the same static module/lesson list regardless of which course
    is open. Making curriculum content vary per-course means adding props
    to those two components -- a separate, larger change.
  - The lesson player (courses\[slug]\learn) now shows the correct course
    title/subtitle at the top, but the module/lesson list inside it is
    still the same static mock content for every course, for the same
    reason as above.
  - Certificates are matched from a small local mock array (mirroring the
    one already used on the certificates list page) since there is no
